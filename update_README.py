"""Generate split solution indexes from local files and problems.json, offline."""
from __future__ import annotations

import argparse
from collections import defaultdict
import html
import json
from pathlib import Path
import re
import sys

LANGUAGES = {
    '.cpp': 'C++', '.c': 'C', '.java': 'Java', '.py': 'Python',
    '.gs': 'Golfscript', '.swift': 'Swift', '.f': 'Fortran', '.ada': 'Ada',
    '.bas': 'FreeBASIC', '.a68': 'Algol 68', '.vb': 'Visual Basic', '.txt': 'Text',
}
GENERATED = '<!-- Generated by update_README.py. Edit problems.json for titles and levels. -->\n\n'


def number_name(number):
    return f'{number:05d}'


def bucket_name(number):
    return f'{number // 1000:02d}xxx'


def label(text):
    return html.escape(text, quote=False).replace('|', r'\|').replace('[', r'\[').replace(']', r'\]')


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'duplicate metadata key: {key}')
        result[key] = value
    return result


def read_metadata(root):
    data = json.loads((root / 'problems.json').read_text(encoding='utf-8'), object_pairs_hook=unique_object)
    if not isinstance(data, dict):
        raise ValueError('problems.json must be an object keyed by padded problem number')
    result = {}
    for key, item in data.items():
        if not key.isascii() or not key.isdigit() or int(key) < 1 or key != number_name(int(key)):
            raise ValueError(f'invalid metadata problem number: {key}')
        if not isinstance(item, dict) or set(item) != {'title', 'level'}:
            raise ValueError(f'{key}: metadata requires title and level')
        title, level = item['title'], item['level']
        if not isinstance(title, str) or not title.strip() or '\n' in title or '\r' in title:
            raise ValueError(f'{key}: title must be a nonempty single line')
        if level is not None and (type(level) is not int or not 0 <= level <= 30):
            raise ValueError(f'{key}: level must be null or an integer from 0 to 30')
        result[int(key)] = item
    return result


def read_solutions(root):
    result = {}
    for bucket in sorted(root.iterdir()):
        if not re.fullmatch(r'\d{2,}xxx', bucket.name):
            continue
        if not bucket.is_dir() or bucket.is_symlink():
            raise ValueError(f'invalid number directory: {bucket.name}')
        count = 0
        for problem in sorted(bucket.iterdir()):
            if problem.name == 'README.md' and problem.is_file() and not problem.is_symlink():
                continue
            key = problem.name
            if not key.isascii() or not key.isdigit() or int(key) < 1 or key != number_name(int(key)):
                raise ValueError(f'noncanonical problem directory: {problem.relative_to(root)}')
            number = int(key)
            if bucket.name != bucket_name(number) or not problem.is_dir() or problem.is_symlink():
                raise ValueError(f'wrong problem location: {problem.relative_to(root)}')
            files = sorted(problem.iterdir(), key=lambda p: (p.suffix, p.name))
            if not files:
                raise ValueError(f'empty problem directory: {problem.relative_to(root)}')
            for source in files:
                valid_name = re.fullmatch(re.escape(key) + r'(?:-alt(?:-(?:[2-9]|[1-9]\d+))?)?' + re.escape(source.suffix), source.name)
                if not source.is_file() or source.is_symlink() or source.suffix not in LANGUAGES or not valid_name:
                    raise ValueError(f'noncanonical submission file: {source.relative_to(root)}')
            if number in result:
                raise ValueError(f'duplicate problem number: {number}')
            result[number] = files
            count += 1
        if not count:
            raise ValueError(f'empty number directory: {bucket.name}')
    if not result:
        raise ValueError('no submission files found')
    return result


def difficulty(level):
    if level is None:
        return '—'
    name = 'Unrated' if level == 0 else f'{["Bronze", "Silver", "Gold", "Platinum", "Diamond", "Ruby"][(level - 1) // 5]} {5 - (level - 1) % 5}'
    return f'<img alt="{name}" src="../assets/{level}.svg" height="24">'


def build_readmes(root):
    metadata, solutions = read_metadata(root), read_solutions(root)
    if metadata.keys() != solutions.keys():
        missing = sorted(solutions.keys() - metadata.keys())
        extra = sorted(metadata.keys() - solutions.keys())
        raise ValueError(f'metadata/source mismatch: missing metadata={missing}, missing source={extra}')
    buckets = defaultdict(list)
    for number in sorted(solutions):
        buckets[bucket_name(number)].append(number)
    top = GENERATED + '# Baekjoon Online Judge Solutions\n\n'
    top += '| 번호 구간 | 문제 수 |\n| --- | ---: |\n'
    output = {}
    for bucket, numbers in sorted(buckets.items(), key=lambda item: int(item[0][:-3])):
        low = int(bucket[:-3]) * 1000
        interval = f'{number_name(low)}–{number_name(low + 999)}'
        top += f'| [{interval}](./{bucket}/README.md) | {len(numbers):,} |\n'
        body = GENERATED + f'# BOJ {interval}\n\n[전체 구간](../README.md)\n\n'
        body += '| No. | Title | Difficulty | Solution |\n| --- | --- | --- | --- |\n'
        for number in numbers:
            links = []
            for source in solutions[number]:
                language = LANGUAGES[source.suffix]
                variant = source.stem.removeprefix(number_name(number))
                if variant:
                    language += f' ({variant.lstrip("-")})'
                links.append(f'[{language}](./{number_name(number)}/{source.name})')
            item = metadata[number]
            body += f'| [{number_name(number)}](https://www.acmicpc.net/problem/{number}) | {label(item["title"])} | {difficulty(item["level"])} | {" ".join(links)} |\n'
        output[Path(bucket) / 'README.md'] = body
    top += '\n## 풀이 추가\n\n'
    top += '코드를 `01xxx/01000/01000.cpp` 형식으로 저장하고 [problems.json](./problems.json)에 제목과 난이도를 추가합니다. `python3 update_README.py`로 목록을 갱신합니다.\n'
    output[Path('README.md')] = top
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--check', action='store_true', help='report stale indexes without writing')
    args = parser.parse_args(argv)
    try:
        output = build_readmes(args.root)
        stale = [p for p, text in output.items() if not (args.root / p).is_file() or (args.root / p).read_bytes() != text.encode('utf-8')]
        if args.check:
            if stale:
                print('Stale indexes: ' + ', '.join(map(str, stale)), file=sys.stderr)
                return 1
            print(f'Indexes are current: {len(output)} README files')
            return 0
        for relative in stale:
            (args.root / relative).write_bytes(output[relative].encode('utf-8'))
        print(f'Generated {len(output)} README files; changed {len(stale)}')
        return 0
    except (OSError, ValueError) as error:
        print(f'Index generation failed: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
